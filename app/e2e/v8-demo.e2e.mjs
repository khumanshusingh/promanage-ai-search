// Rehearses ProManage Product Demo Script v8 (audit-first) scene by scene, plus PRD v7 edge cases.
// Usage: dev server on :5173, then `node e2e/v8-demo.e2e.mjs` (SHOTS=<dir> to save screenshots).
import { start, sleep } from './harness.mjs'

const t = await start()
const { check, step, go, click, has, text, state, ev, exists } = t
const SHOTS = process.env.SHOTS
const WF_DISC = '[id="disc:disc-aud-001-whitefield"]'
const WF_ACC = '[id="acc:issue-saturday-tours"]'

try {
  await go('/')
  await t.clearState()

  step('Scene 0–1 · Meet the customer: Detect landing (fresh load)')
  await go('/')
  check('Fresh load opens 01 Detect', (await t.path()) === '/detect')
  const nav = await ev('[...document.querySelectorAll("aside nav a")].map((a) => a.innerText.replace(/\\s+/g, " ").trim())')
  check('Three always-clickable chapters with MVP/V1/V2 labels', nav.length === 3 && /Detect MVP/.test(nav[0]) && /Improve V1/.test(nav[1]) && /Measure V2/.test(nav[2]), JSON.stringify(nav))
  check('No release toggle or role switch in Brand UI', !(await has('View as')) && !(await ev('!!document.querySelector("[aria-label=Release]")')))
  check('Headline', await has('Understand how AI search represents your locations.'))
  check('Prominent Run CTA up top; no question/location lists upfront', (await exists('Run AI Visibility Check')) && !(await has('Choose locations to check')) && !(await ev('!!document.querySelector("#locations")')))
  check('No mandatory custom question before the check', !(await exists('Save visibility goal')))
  check('Simulated qualifier on the CTA', await has('simulated demo check'))
  await t.shot(SHOTS, '01-detect-landing')

  step('Scene 2 · Click Run → review defaults, optionally adjust, start')
  await click('Run AI Visibility Check')
  check('Review step shows curated questions summary', (await has('Questions parents may ask')) && (await has('5 discoverability (unbranded) · 3 information accuracy (branded)')) && (await has('not search-volume data')))
  await click('Change questions')
  const discEx = await has('Best Montessori preschools in Whitefield, Bengaluru?')
  await click('Information accuracy · 3')
  check('Curated questions grouped Discovery vs Accuracy, both shown', discEx && (await has('Does BrightNest Whitefield offer Saturday campus tours?')) && !(await has('most searched')))
  await click('Being found (Discoverability)')
  await t.type('input[aria-label="Add your own question"]', 'Preschools with transport near Whitefield')
  await click('Add question')
  const sq = await state()
  const custom = sq.customPrompts.find((c) => c.text.includes('transport'))
  check('Brand can add its own question (templated per centre)', !!custom && custom.text.includes('{neighborhood}') && sq.detectPromptIds.includes(custom.id))
  await click(`Remove ${custom.text}`)
  check('Own question can be removed', !(await state()).customPrompts.some((c) => c.text.includes('transport')))
  await click('Change locations')
  await t.type('input[aria-label="Search centres to add"]', 'Baner')
  await click('BrightNest Baner')
  check('Brand can add another of its centres', (await state()).detectLocationIds.includes('baner-pune'))
  await click('Remove BrightNest Baner')
  check('10 pilot centres preselected', (await ev('document.querySelectorAll("#locations button[role=checkbox][data-state=checked]").length')) === 10)
  await click('Marathahalli', { within: '#locations' })
  check('Location can be deselected', (await state()).detectLocationIds?.length === 9)
  await click('Marathahalli', { within: '#locations' })
  await t.shot(SHOTS, '01b-review-check')
  await click('Start check')
  check('Progress state shown', await has('Checking selected questions') || await has('Sampling answers'))
  await sleep(5200)
  check('Findings ready', await has('Your AI visibility findings are ready'))
  const s1 = await state()
  check('One standard audit created from existing engine (10 centres × 8 questions)', s1.audits.length === 1 && s1.audits[0].locationIds.length === 10 && s1.audits[0].promptIds.length === 8)
  check('Discovery denominator excludes branded accuracy prompts', /\b(\d+) of (\d+)\b/.test(await text()) && Number((await text()).match(/(\d+) of (\d+)\s*eligible/)?.[2] ?? 99) <= 50)
  check('No approvals or publications yet', !(s1.approvals?.length) && !(s1.publications?.length))

  step('Scene 3 · Whitefield: one discovery + one accuracy finding')
  await t.select('select[aria-label="Location"]', 'whitefield')
  check('Discovery finding on unbranded Montessori prompt', (await has('“Best Montessori preschools in Whitefield, Bengaluru”')) && (await has('Discovery opportunity')))
  check('Accuracy finding on branded Saturday-tour prompt', (await has('“Does BrightNest Whitefield offer Saturday campus tours?”')) && (await has('Accuracy finding')))
  check('AI said vs verified record', (await has('No Saturday tours')) && (await has('Saturday tours 10 AM–1 PM')))
  check('Non-mention framed as opportunity, not error', await has('Not mentioned isn’t necessarily an error'))
  await click('Details')
  await click('View original AI answer')
  check('Original AI answer evidence opens in the detail panel', await has('Question asked:'))
  await t.shot(SHOTS, '02-detect-whitefield')

  step('Scene 4 · Click 02 Improve → V1 unlocks, both proposals ready')
  await click('02 · Improve')
  await sleep(500)
  check('Navigated to Improve', (await t.path()) === '/improve')
  const s2 = await state()
  check('V1 unlocked cumulatively', s2.release === 'V1')
  check('Opening Improve approved/published nothing', !(s2.approvals?.length) && !(s2.publications?.length))
  check('Discovery proposal ready for Whitefield', (await has('BrightNest Whitefield — help parents find your centre')) && s2.discovery['disc-aud-001-whitefield']?.plan?.status === 'awaiting_brand_approval')
  check('Accuracy proposal ready for Whitefield', (await has('BrightNest Whitefield — correct Saturday tour availability')) && s2.plans['issue-saturday-tours']?.status === 'awaiting_brand_approval')
  check('Fixes are the prominent block with one authorize bar', (await has('recommended fixes')) && (await exists('Approve & authorize')))
  await click('What ProManage checked', { within: WF_DISC })
  check('Confirmed gap vs hypothesized impact distinguished', await has('Whether they caused the AI to leave you out is a hypothesis'))
  check('No-gap case reported honestly (UC-04)', await has('No confirmed, controllable gap found'))

  step('Scene 5 · Review before/after and technical details')
  check('Exact before/after for discovery', await ev(`(() => { const t = document.querySelector('${WF_DISC}')?.innerText ?? ''; return /NOW/i.test(t) && /AFTER/i.test(t) && t.includes('Montessori programme (Nursery–UKG)') })()`))
  await click('Technical details prepared by ProManage', { within: WF_DISC })
  check('Read-only JSON-LD visible with validation', (await ev(`document.querySelector('${WF_DISC} pre[aria-label="JSON-LD preview"]')?.innerText.includes('"@context"')`)) && (await has('Validated against verified facts')))
  check('No raw-code editing for Brand', !(await ev(`!!document.querySelector('${WF_DISC} pre[aria-label="JSON-LD preview"] textarea, ${WF_DISC} textarea[aria-label*="JSON"]')`)))
  check('What we cannot change automatically', await has('What we cannot change automatically'))
  await click('Technical details prepared by ProManage', { within: WF_DISC })
  await t.shot(SHOTS, '03-improve-whitefield')

  step('Scene 6 · Approve & authorize → simulated per-target publication')
  await click('Approve & authorize', { within: WF_DISC })
  check('Authorization dialog lists exact targets', await has('Here is exactly what will change'))
  await click('Authorize selected targets')
  await sleep(1500)
  const s3 = await state()
  const wfPubs = s3.publications.filter((p) => p.proposalKey === 'disc:disc-aud-001-whitefield')
  check('Connected targets published (simulated)', wfPubs.filter((p) => p.state === 'success').length === 2, JSON.stringify(wfPubs.map((p) => p.state)))
  check('Site-admin target not marked published', wfPubs.some((p) => p.state === 'blocked'))
  check('Third-party directory is a handoff, not a success', wfPubs.some((p) => p.state === 'manual_handoff'))
  check('Per-target statuses shown', (await has('Updated (simulated)')) && (await has('External handoff')) && (await has('Demo: simulated publication')))
  await click('BrightNest Whitefield — correct Saturday tour availability')
  check('Exact before/after for accuracy', (await has('Weekday campus visits only (9 AM–4 PM)')) && (await ev(`/after/i.test(document.querySelector('${WF_ACC}')?.innerText ?? '')`)))
  await click('Approve & authorize', { within: WF_ACC })
  await click('Authorize selected targets')
  await sleep(1500)
  const s4 = await state()
  check('Accuracy correction published to connected website', s4.publications.some((p) => p.proposalKey === 'acc:issue-saturday-tours' && p.state === 'success'))
  check('Website snapshot updated, AI answer untouched', s4.sourceUpdates['whitefield-web:saturdayTours']?.value === 'Saturday tours 10 AM–1 PM')
  check('Idempotent: re-applying adds no duplicate attempts', s4.publications.filter((p) => p.proposalKey === 'acc:issue-saturday-tours').length === new Set(s4.publications.filter((p) => p.proposalKey === 'acc:issue-saturday-tours').map((p) => p.taskId)).size)
  await t.shot(SHOTS, '04-improve-published')

  step('UC-06/07 · Decline, request changes, partial failure + retry')
  await click('BrightNest HSR Layout — correct opening hours')
  await click('Decline', { within: '[id="acc:issue-hsr-hours"]', exact: true })
  await t.type('textarea[aria-label="Comment"]', 'Hold until the new timetable is final.')
  await click('Decline', { exact: true, nth: 1 })
  const s5 = await state()
  check('Decline publishes nothing', s5.plans['issue-hsr-hours'].status === 'declined' && !s5.publications.some((p) => p.proposalKey === 'acc:issue-hsr-hours'))
  await click('BrightNest Indiranagar — help parents find your centre')
  await click('Request changes', { within: '[id="disc:disc-aud-001-indiranagar"]' })
  await t.type('textarea[aria-label="Comment"]', 'Please mention the toddler playgroup.')
  await click('Send request')
  check('Request changes publishes nothing', (await state()).discovery['disc-aud-001-indiranagar'].plan.status === 'changes_requested' && !(await state()).publications.some((p) => p.proposalKey.includes('indiranagar')))
  await click('See revised version')
  check('Revised version needs new authorization', (await state()).discovery['disc-aud-001-indiranagar'].plan.status === 'awaiting_brand_approval' && (await state()).discovery['disc-aud-001-indiranagar'].plan.round === 2)
  await click('BrightNest Marathahalli — correct open / closed status')
  await click('Approve & authorize', { within: '[id="acc:iss-aud-001-marathahalli-p8-mismatch"]' })
  await click('Authorize selected targets')
  await sleep(1500)
  check('Partial failure shown honestly (connector credential expired)', (await has('Failed — ProManage follow-up')) && (await state()).publications.some((p) => p.state === 'failed'))
  await click('ProManage follow-up: retry')
  check('Retry succeeds within same approval scope', (await state()).publications.filter((p) => p.proposalKey.includes('marathahalli') && p.state === 'success').length === 1)

  step('Scene 7 · Click 03 Measure → V2 unlocks; two separate lenses')
  await click('03 · Measure')
  await sleep(900)
  const s6 = await state()
  check('V2 unlocked; MVP and V1 still reachable', s6.release === 'V2')
  check('ProManage ran a matched follow-up after published updates', s6.rechecks.length === 1)
  check('Before vs after section with both deltas', (await has('Before and after your changes')) && (await has('Discoverability')) && (await has('incorrect answers')))
  check('Discoverability rises, inaccurate answers fall (from fixtures)', await ev(`(() => { const b = [...document.querySelectorAll('span')].map((e) => e.innerText); return b.some((x) => /^\\+\\d+ mentions$/.test(x.trim())) && b.some((x) => /^-\\d+ incorrect answers$/.test(x.trim())) })()`))
  check('Source updates separated from AI outcomes', (await has('What changed on your sources')) && (await has('Discoverability')) && (await has('Information accuracy')))
  const m = await text()
  check('Whitefield discovery n/N from fixtures (3 of 5 → 5 of 5)', m.includes('3 of 5') && m.includes('5 of 5'))
  check('Whitefield Saturday-tour accuracy: no mismatch in latest sampled check', await has('No mismatch in latest sampled check'))
  check('Persisting issue stays visible (Marathahalli status still appears)', await has('Incorrect statement still appears'))
  check('No causal / guarantee language', (await has('not proof')) && !(await has('guaranteed')))
  check('Timeline present', await has('Timeline') && await has('You authorized'))
  await t.shot(SHOTS, '05-measure')

  step('Scene 8 · Optional: Target a specific question')
  await click('01 · Detect')
  await click('Target a specific question')
  await t.type('#goal-q', 'Best preschools in Whitefield for three-year-olds?')
  await click('Save visibility goal')
  const g = (await state()).goals.find((x) => x.anchorQuestion.includes('three-year-olds'))
  check('Goal saved, scoped to Whitefield, versioned', !!g && g.locationIds[0] === 'whitefield' && g.goalVersion === 1)
  check('Unseeded question shows Awaiting first check (no fabricated result)', (await has('Awaiting first check — no demo sample for this question')) && !g.promptId)
  check('Header offers Back to standard check', await has('Back to standard check'))
  await t.shot(SHOTS, '06-target-question')
  await click('Whitefield Priority Question')
  check('Seeded goal links exact-question evidence, kept separate from variants', (await has('Exact-question sample: 0/1 baseline')) && (await has('Kept separate')))

  step('Scene 9 · Back to standard check; refresh keeps everything')
  await click('Back to standard check')
  check('Standard view restored', (await state()).selectedGoalId === null && (await has('All locations · All findings · Latest standard check')))
  await t.reload()
  const s7 = await state()
  check('After refresh: unlocks, approvals, publications, rechecks persist', s7.release === 'V2' && s7.approvals.length >= 4 && s7.publications.length > 0 && s7.rechecks.length === 1)
  check('Original Whitefield Montessori answer still a non-mention (immutable)', await (async () => { await t.select('select[aria-label="Location"]', 'whitefield'); return (await has('“Best Montessori preschools in Whitefield, Bengaluru”')) && (await has('Not mentioned in sampled recommendations')) })())
  await go('/improve#acc:issue-saturday-tours')
  check('Deep link to Improve works after reload', (await t.path()) === '/improve' && (await has('Authorized')))
  await t.back()
  check('Back navigation works', (await t.path()) === '/detect')

  step('Edge · V2 first on a fresh check (no approval, no fake victory)')
  await t.clearState()
  await go('/detect')
  await click('Run AI Visibility Check')
  await click('Start check')
  await sleep(5200)
  await go('/measure')
  await sleep(600)
  const s8 = await state()
  check('Measure first unlocks V2 (and V1) without approving', s8.release === 'V2' && !(s8.approvals?.length) && !(s8.publications?.length) && !(s8.rechecks?.length))
  check('Honest pending state', await has('No approved changes to measure yet'))
  await go('/improve')
  check('Proposals still await authorization', await has('Awaiting your authorization'))

  step('Regression · legacy routes and internal ProManage workspace')
  for (const r of ['/overview', '/locations', '/attention', '/progress', '/reports', '/locations/whitefield/answers', '/attention/discovery/disc-aud-001-whitefield', '/attention/issue-saturday-tours']) {
    await go(r)
    check(`Brand route ${r} renders`, !(await has('Page not found')) && (await text()).length > 50)
  }
  await ev(`(() => { const k = 'promanage-ai-visibility-demo'; const s = JSON.parse(localStorage.getItem(k)); s.role = 'promanage'; localStorage.setItem(k, JSON.stringify(s)) })()`)
  for (const r of ['/overview', '/issues', '/issues?tab=discovery', '/issues/issue-saturday-tours', '/issues/issue-saturday-tours/sources', '/tasks', '/geo-readiness/whitefield?tab=jsonld', '/geo-readiness/whitefield?tab=content', '/monitoring', '/reports', '/discovery/disc-aud-001-whitefield']) {
    await go(r)
    check(`Internal route ${r} renders`, !(await has('Page not found')) && (await text()).length > 50)
  }
} catch (e) {
  t.failures.push(`ABORTED: ${e.message}`)
  console.log(`  ✗ ABORTED: ${e.message}`)
  await t.shot(SHOTS, 'zz-failure')
}
t.finish()
